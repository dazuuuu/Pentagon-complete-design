<?php

namespace App\Services;

use App\Core\Database;
use App\Helpers\Path;
use App\Models\Admin;
use PDO;
use PDOException;
use RuntimeException;

class SetupService
{
    public function lockPath(): string
    {
        return Path::logic('installed.lock');
    }

    public function isInstalled(): bool
    {
        return is_file($this->lockPath());
    }

    public function markInstalled(string $adminEmail = ''): void
    {
        $payload = json_encode([
            'installed_at' => date('c'),
            'admin_email' => $adminEmail,
        ], JSON_PRETTY_PRINT);
        file_put_contents($this->lockPath(), $payload ?: date('c'));
    }

    /**
     * Write live DB credentials straight into config/database.php — the
     * single file this app reads for its connection. No .env involved.
     *
     * @param array{host:string,port:int|string,name:string,user:string,pass:string} $db
     */
    public function writeDatabaseConfig(array $db): void
    {
        $name = $this->safeDatabaseName($db['name']);
        $contents = "<?php\n\n"
            . "/**\n"
            . " * Database connection — THE single place to edit when you host this site.\n"
            . " * Generated by the /setup wizard. Edit directly any time your credentials change.\n"
            . " */\n\n"
            . "return [\n"
            . "    'host' => " . var_export(trim($db['host']), true) . ",\n"
            . "    'port' => " . (int) $db['port'] . ",\n"
            . "    'name' => " . var_export($name, true) . ",\n"
            . "    'user' => " . var_export($db['user'], true) . ",\n"
            . "    'pass' => " . var_export($db['pass'], true) . ",\n"
            . "    'charset' => 'utf8mb4',\n"
            . "];\n";

        if (file_put_contents(Path::config('database.php'), $contents) === false) {
            throw new RuntimeException('Could not write config/database.php. Check folder permissions on apps/pentagon_quest_logic/config/.');
        }

        Database::reset();
    }

    /**
     * Default admin name/email shown as suggestions on the setup form.
     *
     * @return array{name: string, email: string}
     */
    public function defaultAdmin(): array
    {
        $defaults = require Path::config('admin.php');
        return [
            'name' => (string) ($defaults['name'] ?? 'Site Admin'),
            'email' => (string) ($defaults['email'] ?? 'admin@pentagonsafaris.com'),
        ];
    }

    /**
     * Create the database if needed, then connect to it.
     *
     * @param array{host:string,port:int|string,name:string,user:string,pass:string} $db
     */
    public function prepareDatabase(array $db): void
    {
        $name = $this->safeDatabaseName($db['name']);
        $host = trim($db['host']);
        $port = (int) $db['port'];
        $user = $db['user'];
        $pass = $db['pass'];

        try {
            $server = new PDO(
                sprintf('mysql:host=%s;port=%d;charset=utf8mb4', $host, $port),
                $user,
                $pass,
                [
                    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                    PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
                ]
            );
        } catch (PDOException $e) {
            throw new RuntimeException('Could not connect to MySQL: ' . $e->getMessage());
        }

        $server->exec('CREATE DATABASE IF NOT EXISTS `' . $name . '` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci');
        $server = null;

        $this->writeDatabaseConfig($db);
        Database::connection();
    }

    /**
     * Apply complete CREATE TABLE files from database/required_migrations.
     * Setup passes $resetSchema = true so leftover mixed/partial tables are dropped first.
     *
     * @return list<string>
     */
    public function runMigrations(bool $resetSchema = false): array
    {
        $db = Database::connection();
        $updateService = new UpdateService();
        $updateService->ensureTrackingTables();

        if ($resetSchema) {
            $this->resetSchema($db);
            $updateService->ensureTrackingTables();
        }

        $applied = [];
        $files = glob(Path::requiredMigrations() . DIRECTORY_SEPARATOR . '*.sql') ?: [];
        sort($files);

        if ($files === []) {
            throw new RuntimeException('No SQL files found in database/required_migrations.');
        }

        foreach ($files as $file) {
            $filename = basename($file);
            if ($updateService->isMigrationApplied($filename)) {
                $applied[] = $filename . ' (already applied)';
                continue;
            }
            $sql = file_get_contents($file);
            if ($sql === false) {
                throw new RuntimeException('Could not read migration ' . $filename);
            }
            $db->exec($sql);
            $updateService->markMigrationApplied($filename);
            $applied[] = $filename;
        }

        return $applied;
    }

    /**
     * List required_migrations files and whether each has been applied yet,
     * without running anything. Used by the admin "run migrations" screen.
     *
     * @return list<array{filename: string, pending: bool}>
     */
    public function requiredMigrationsCatalog(): array
    {
        $updateService = new UpdateService();
        $updateService->ensureTrackingTables();

        $files = glob(Path::requiredMigrations() . DIRECTORY_SEPARATOR . '*.sql') ?: [];
        sort($files);

        $items = [];
        foreach ($files as $file) {
            $filename = basename($file);
            $items[] = [
                'filename' => $filename,
                'pending' => !$updateService->isMigrationApplied($filename),
            ];
        }

        return $items;
    }

    public function seed(): void
    {
        $seedFile = Path::database('seeds', 'seed_initial_data.sql');
        if (!is_file($seedFile)) {
            return;
        }

        $db = Database::connection();
        $seedSql = file_get_contents($seedFile) ?: '';
        foreach (explode(';', $seedSql) as $raw) {
            $statement = $this->stripSqlComments(trim($raw));
            if ($statement === '') {
                continue;
            }
            try {
                $db->exec($statement);
            } catch (PDOException $e) {
                if (strpos($e->getMessage(), 'Duplicate') === false) {
                    throw $e;
                }
            }
        }
    }

    /**
     * @return list<array{filename: string, success: bool, message: string}>
     */
    public function runUpdates(): array
    {
        return (new UpdateService())->applyPending();
    }

    public function adminExists(): bool
    {
        try {
            $count = (int) Database::connection()->query('SELECT COUNT(*) FROM admins')->fetchColumn();
            return $count > 0;
        } catch (PDOException) {
            return false;
        }
    }

    /**
     * @return array{id:int,name:string,email:string}
     */
    public function createAdmin(string $name, string $email, string $password): array
    {
        $name = trim($name);
        $email = trim($email);
        if ($name === '' || $email === '' || $password === '') {
            throw new RuntimeException('Admin name, email, and password are required.');
        }
        if (!filter_var($email, FILTER_VALIDATE_EMAIL)) {
            throw new RuntimeException('Please enter a valid admin email address.');
        }
        if (strlen($password) < 8) {
            throw new RuntimeException('Admin password must be at least 8 characters.');
        }

        $model = new Admin();
        $existing = $model->findByEmail($email);
        $hash = password_hash($password, PASSWORD_DEFAULT);
        if ($existing) {
            $stmt = Database::connection()->prepare('UPDATE admins SET name = ?, password_hash = ? WHERE id = ?');
            $stmt->execute([$name, $hash, $existing['id']]);
            return ['id' => (int) $existing['id'], 'name' => $name, 'email' => $email];
        }

        $id = $model->create($name, $email, $hash);
        return ['id' => $id, 'name' => $name, 'email' => $email];
    }

    /**
     * Drop app tables so CREATE IF NOT EXISTS cannot skip an incomplete leftover schema.
     */
    private function resetSchema(PDO $db): void
    {
        $tables = [
            'testimonials',
            'clients',
            'enquiries',
            'offers',
            'experience_images',
            'destination_images',
            'tour_images',
            'tours',
            'destinations',
            'gallery',
            'subscribers',
            'blog_posts',
            'service_offerings',
            'service_tiers',
            'experiences',
            'featured_packages',
            'posters',
            'home_settings',
            'admins',
            'schema_migrations',
            'schema_updates',
        ];

        $db->exec('SET FOREIGN_KEY_CHECKS=0');
        foreach ($tables as $table) {
            $db->exec('DROP TABLE IF EXISTS `' . $table . '`');
        }
        $db->exec('SET FOREIGN_KEY_CHECKS=1');
    }

    private function stripSqlComments(string $statement): string
    {
        $lines = [];
        foreach (preg_split('/\R/', $statement) ?: [] as $line) {
            if (str_starts_with(ltrim($line), '--')) {
                continue;
            }
            $lines[] = $line;
        }

        return trim(implode("\n", $lines));
    }

    private function safeDatabaseName(string $name): string
    {
        $name = trim($name);
        if ($name === '' || !preg_match('/^[A-Za-z0-9_]+$/', $name)) {
            throw new RuntimeException('Database name may only contain letters, numbers, and underscores.');
        }
        return $name;
    }
}
